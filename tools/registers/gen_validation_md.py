#!/usr/bin/env python3
"""Generate docs/validation.md from protocol/registers.json and telemetry.json.

Usage:
    uv run --project tools/registers tools/registers/gen_validation_md.py > docs/validation.md
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

HEADER = """# Validation checklist

Generated by `tools/registers/gen_validation_md.py`. Fill `verified` with
`yes`, `no`, or `wrong` while connected to the real controller; explain any
`wrong` in `note`. A register's `confidence` in `registers.json` is raised to
`high` only after a `yes` here.

"""


def render(registers: list[dict], telemetry: list[dict]) -> str:
    out = [
        HEADER,
        "## Registers\n\n",
        "| addr | key | name | confidence | verified | note |\n",
        "|---|---|---|---|---|---|\n",
    ]
    for entry in sorted(registers, key=lambda e: e["addr"]):
        out.append(
            f"| 0x{entry['addr']:02X} | {entry['key']} | {entry['name']} | "
            f"{entry['confidence']} |  |  |\n"
        )

    out.extend(
        [
            "\n## Telemetry\n\n",
            "| frame+offset | key | name | confidence | verified | note |\n",
            "|---|---|---|---|---|---|\n",
        ]
    )
    for entry in sorted(telemetry, key=lambda e: (e["frame"], e["offset"])):
        out.append(
            f"| {entry['frame']}+{entry['offset']} | {entry['key']} | "
            f"{entry['name']} | {entry['confidence']} |  |  |\n"
        )
    return "".join(out)


def main() -> int:
    registers = json.loads((ROOT / "protocol/registers.json").read_text())
    telemetry = json.loads((ROOT / "protocol/telemetry.json").read_text())
    sys.stdout.write(render(registers, telemetry))
    return 0


if __name__ == "__main__":
    sys.exit(main())
